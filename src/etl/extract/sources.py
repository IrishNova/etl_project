"""Level 1 — Extract.

Load each raw source file into a DataFrame, as faithfully as possible.
No cleaning, no type conversion, no reshaping — that is Level 2 (Transform).

Everything is read as text (dtype=str / no header guessing) on purpose:
letting pandas infer types here would silently mangle the very messiness we
want to handle deliberately later (Excel serial dates, "4 seats", leading
zeros on account numbers, etc.). We keep the raw truth and type it in L2.
"""

from pathlib import Path

import pandas as pd

# _data/ lives at the project root, three levels up from this file:
#   src/etl/extract/sources.py -> src/etl/extract -> src/etl -> src -> root
DATA_DIR = Path(__file__).resolve().parents[3] / "_data"

PRODUCT_A_PATH = DATA_DIR / "product_a_legacy_licenses.csv"
PRODUCT_B_PATH = DATA_DIR / "product_b_cad_subscriptions.csv"
PRODUCT_C_PATH = DATA_DIR / "product_c_simulation_orders.xlsx"


# keep_default_na=False + na_values=[] stop pandas from turning the literal
# string "NA" (North America, in the region columns) into a missing value.
# We load as faithful text and decide what counts as "missing" ourselves in L2.
_NO_NA_COERCION = dict(keep_default_na=False, na_values=[])


def load_product_a() -> pd.DataFrame:
    """Product A — legacy licenses (CSV, has a proper header row)."""
    return pd.read_csv(PRODUCT_A_PATH, dtype=str, **_NO_NA_COERCION)


def load_product_b() -> pd.DataFrame:
    """Product B — CAD subscriptions (CSV, has a proper header row).

    Read with the default C engine so quoted fields containing commas
    (e.g. "Vertex Aerospace, LLC") are parsed correctly, not split.
    """
    return pd.read_csv(PRODUCT_B_PATH, dtype=str, **_NO_NA_COERCION)


def load_product_c() -> pd.DataFrame:
    """Product C — simulation orders (XLSX).

    The first two rows are a junk preamble (title + 'Generated by SalesOps'),
    and the real header sits on row 3. We load with header=None so those rows
    arrive as plain data — nothing hidden — and strip them in Transform.
    """
    return pd.read_excel(PRODUCT_C_PATH, header=None, dtype=str)


def load_all() -> dict[str, pd.DataFrame]:
    """Load all three raw sources, keyed by product letter."""
    return {
        "A": load_product_a(),
        "B": load_product_b(),
        "C": load_product_c(),
    }


if __name__ == "__main__":
    # Quick smoke test: load everything and report what we got.
    for key, df in load_all().items():
        print(f"\n===== Product {key} =====")
        print(f"shape: {df.shape[0]} rows x {df.shape[1]} cols")
        print(f"columns: {list(df.columns)}")
        print(df.head(3).to_string())
